'use strict';
/*
 * Builds ParkSmart Mobile from the SAME source as the laptop app.
 *   node mobile/build-mobile.js
 * Output:
 *   mobile/www/                        -> app files (packed into the Android APK as assets)
 *   mobile/dist/ParkSmart-Mobile.html  -> the whole app in ONE file (open in any phone browser)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUB = path.join(ROOT, 'public');
const SRV = path.join(ROOT, 'server');
const SRC = path.join(__dirname, 'src');
const WWW = path.join(__dirname, 'www');
const DIST = path.join(__dirname, 'dist');

const rd = (p) => fs.readFileSync(p, 'utf8');
function wr(p, s) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); }
function rmrf(p) { if (fs.existsSync(p)) fs.rmSync(p, { recursive: true, force: true }); }
function mustReplace(s, a, b, label) {
  if (s.indexOf(a) < 0) throw new Error('build: could not find text to replace (' + label + ')');
  return s.split(a).join(b);
}

// 1. engine: on-phone core + the laptop's own server.js / seed.js / rng.js
let engine = '/* ParkSmart Mobile engine — generated by mobile/build-mobile.js from server/*.js. Do not edit by hand. */\n' + rd(path.join(SRC, 'local-core.js')) + '\n';
for (const m of ['rng', 'seed', 'server']) {
  engine += `PS_define('./${m}', function (module, exports, require, __dirname) {\n${rd(path.join(SRV, m + '.js'))}\n});\n`;
}
engine += rd(path.join(SRC, 'boot.js'));

// 2. index.html for the phone
let html = rd(path.join(PUB, 'index.html'));
html = mustReplace(html, '<meta name="viewport" content="width=device-width, initial-scale=1">', '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">', 'viewport');
html = mustReplace(html, '<title>ParkSmart Puducherry</title>', '<title>ParkSmart Mobile</title>', 'title');
html = mustReplace(html, '<link rel="stylesheet" href="css/app.css">', '<link rel="stylesheet" href="css/app.css">\n<link rel="stylesheet" href="css/mobile.css">', 'css');
html = mustReplace(html, '<script src="js/common.js"></script>', '<script src="js/engine.js"></script>\n<script src="js/common.js"></script>\n<script src="js/mobile.js"></script>', 'engine');

// 3. small source patches for the phone
let common = rd(path.join(PUB, 'js', 'common.js'));
common = mustReplace(common, '  function printModal() {\n', '  function printModal() {\n    if (window.PS_MOBILE && PS_MOBILE.printModal) return PS_MOBILE.printModal();\n', 'printModal');
let app = rd(path.join(PUB, 'js', 'app.js'));
app = mustReplace(app, "      { id: 'about', label: 'About'",
  "      { id: 'sync', label: 'Phone & Sync', icon: 'phone', public: true, section: 'Help', render: function (m) { window.PS_MOBILE.viewSync(m); } },\n      { id: 'about', label: 'About'", 'sync view');
app = mustReplace(app, "<li>Runs on one laptop (Node.js, no internet needed); phones connect over Wi-Fi.</li>",
  "<li><b>ParkSmart Mobile:</b> the whole system runs inside this phone — no laptop, server or Wi-Fi link needed. Reports can be sent to the laptop with a sync file.</li>", 'about');
app = mustReplace(app, "footer: 'ParkSmart · PS-03 prototype'", "footer: 'ParkSmart Mobile · PS-03 prototype'", 'footer');

// 4. write www/
rmrf(WWW);
wr(path.join(WWW, 'index.html'), html);
wr(path.join(WWW, 'js', 'engine.js'), engine);
wr(path.join(WWW, 'js', 'common.js'), common);
wr(path.join(WWW, 'js', 'app.js'), app);
wr(path.join(WWW, 'js', 'mobile.js'), rd(path.join(SRC, 'mobile.js')));
wr(path.join(WWW, 'css', 'mobile.css'), rd(path.join(SRC, 'mobile.css')));
const COPY = ['css/base.css', 'css/app.css', 'js/cctv.js', 'js/realcctv.js', 'lib/leaflet/leaflet.css', 'lib/leaflet/leaflet.js', 'lib/chart.umd.js', 'lib/qrcode.js',
  // offline number plate reader (OCR) — runs inside the phone
  'lib/ocr/tesseract.min.js', 'lib/ocr/worker.min.js', 'lib/ocr/plate-ocr.js', 'lib/ocr/tesseract-core-lstm.wasm.js', 'lib/ocr/tesseract-core-simd-lstm.wasm.js', 'lib/ocr/eng.traineddata.gz', 'lib/ocr/LICENSE.txt'];
for (const f of COPY) { fs.mkdirSync(path.dirname(path.join(WWW, f)), { recursive: true }); fs.copyFileSync(path.join(PUB, f), path.join(WWW, f)); }
fs.mkdirSync(path.join(WWW, 'lib', 'leaflet', 'images'), { recursive: true });
for (const f of fs.readdirSync(path.join(PUB, 'lib', 'leaflet', 'images'))) fs.copyFileSync(path.join(PUB, 'lib', 'leaflet', 'images', f), path.join(WWW, 'lib', 'leaflet', 'images', f));

// 5. single-file version (everything inlined)
const img = (f) => 'data:image/png;base64,' + fs.readFileSync(path.join(WWW, 'lib', 'leaflet', 'images', f)).toString('base64');
const safeJs = (s) => s.replace(/<\/script/gi, '<\\/script');
// The single-file version cannot carry the 7 MB OCR engine; it simply hides plate reading.
let one = html.replace('<script src="lib/ocr/tesseract.min.js"></script>\n', '').replace('<script src="lib/ocr/plate-ocr.js"></script>\n', '');
one = one.replace(/<link rel="stylesheet" href="([^"]+)">/g, function (_, href) {
  let css = rd(path.join(WWW, href));
  if (href.indexOf('leaflet') >= 0) css = css.replace(/url\(images\/([\w.-]+\.png)\)/g, (m, f) => 'url(' + img(f) + ')');
  return '<style>\n' + css + '\n</style>';
});
one = one.replace(/<script src="([^"]+)"><\/script>/g, function (_, src) {
  let js = rd(path.join(WWW, src));
  if (src === 'lib/leaflet/leaflet.js') js += `\n;L.Icon.Default.imagePath='';L.Icon.Default.mergeOptions({iconUrl:'${img('marker-icon.png')}',iconRetinaUrl:'${img('marker-icon-2x.png')}',shadowUrl:'${img('marker-shadow.png')}'});`;
  return '<script>\n' + safeJs(js) + '\n</script>';
});
if (/(href|src)="(css|js|lib)\//.test(one)) throw new Error('build: single file still references external files');
wr(path.join(DIST, 'ParkSmart-Mobile.html'), one);
console.log('ParkSmart Mobile built:');
console.log('  ' + path.relative(ROOT, WWW) + path.sep + '  (APK assets)');
console.log('  ' + path.relative(ROOT, path.join(DIST, 'ParkSmart-Mobile.html')) + '  (' + Math.round(one.length / 1024) + ' KB, single file)');
